// 3. Find the Sum and Average of 5 Numbers. 

#include<stdio.h>
#include<stdlib.h>

void main(int argc,char *argv[])
{
	float a = atoi(argv[1]);
	float b = atoi(argv[2]);
	float c = atoi(argv[3]);
	float d = atoi(argv[4]);
	float e = atoi(argv[5]);

	printf("Avg=%f",(a+b+c+d+e)/5);	
}
	
